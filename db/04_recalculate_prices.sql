--  Позволяет обновить стоимость услуг через прямой SQL-запрос
--  (например, все услуги дешевле 1500 ₽ поднять до 2000 ₽).
--  Запуск в MySQL Workbench (⚡) или через терминал:
--  mysql -u root lumiere_salon < db/04_recalculate_prices.sql
-- ============================================================
SET NAMES utf8mb4;
USE lumiere_salon;

-- 1. Просмотр текущих цен на услуги до перерасчета
SELECT '--- ЦЕНЫ ДО ПЕРЕРАСЧЕТА ---' AS status;
SELECT id, title, price, duration 
FROM services 
ORDER BY price ASC;

-- ------------------------------------------------------------
-- 2. ПРИМЕР ПЕРЕРАСЧЕТА №1: 
-- Все услуги дешевле 1500 ₽ поднимаем до 2000 ₽
-- (соответствует логике кнопки «Пересчет цен» на сайте)
-- ------------------------------------------------------------
UPDATE services 
SET price = 2000.00 
WHERE price < 1500.00;

-- ------------------------------------------------------------
-- 3. ПРИМЕР ПЕРЕРАСЧЕТА №2:
-- Услуги в заданном диапазоне (например, от 500 ₽ до 1000 ₽)
-- поднять до 1200 ₽
